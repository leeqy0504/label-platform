// ─── Training Metrics ─────────────────────────────────────────────────────────

function generateMetrics(epochs: number, finalMAP: number): MetricPoint[] {
  return Array.from({ length: epochs }, (_, i) => {
    const progress = (i + 1) / epochs;
    const noise = () => (Math.random() - 0.5) * 0.02;
    return {
      epoch: i + 1,
      trainLoss: 2.8 * Math.exp(-3.5 * progress) + 0.15 + noise(),
      valLoss: 3.1 * Math.exp(-3.0 * progress) + 0.20 + noise(),
      mAP50: finalMAP * (1 - Math.exp(-4 * progress)) + noise() * 0.5,
      mAP5095: finalMAP * 0.62 * (1 - Math.exp(-4 * progress)) + noise() * 0.3,
      lr: 0.01 * Math.exp(-2 * progress),
    };
  });
}

